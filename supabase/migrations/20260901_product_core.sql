drop policy if exists profiles_self on public.profiles;
create policy profiles_self on public.profiles for all using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists org_member_read on public.organizations;
create policy org_member_read on public.organizations for select using (public.is_org_member(id));
drop policy if exists org_admin_write on public.organizations;
create policy org_admin_write on public.organizations for all using (public.is_org_admin(id)) with check (public.is_org_admin(id));

drop policy if exists members_read on public.organization_members;
create policy members_read on public.organization_members for select using (public.is_org_member(organization_id));
drop policy if exists members_owner_write on public.organization_members;
create policy members_owner_write on public.organization_members for all using (public.is_org_admin(organization_id)) with check (public.is_org_admin(organization_id));

drop policy if exists storefront_member_all on public.storefronts;
create policy storefront_member_all on public.storefronts for all using (public.is_org_member(organization_id)) with check (public.is_org_member(organization_id));

drop policy if exists category_member_all on public.categories;
create policy category_member_all on public.categories for all using (public.is_org_member(organization_id)) with check (public.is_org_member(organization_id));

drop policy if exists product_member_all on public.products;
create policy product_member_all on public.products for all using (public.is_org_member(organization_id)) with check (public.is_org_member(organization_id));

drop policy if exists image_member_all on public.product_images;
create policy image_member_all on public.product_images for all using (
  exists (select 1 from public.products p where p.id = product_id and public.is_org_member(p.organization_id))
) with check (
  exists (select 1 from public.products p where p.id = product_id and public.is_org_member(p.organization_id))
);

drop policy if exists analytics_member_read on public.analytics_events;
create policy analytics_member_read on public.analytics_events for select using (public.is_org_member(organization_id));
drop policy if exists analytics_insert_public on public.analytics_events;
create policy analytics_insert_public on public.analytics_events for insert with check (
  event_type in ('store_view','product_view','product_click')
  and exists (select 1 from public.storefronts s where s.organization_id = organization_id and s.status = 'published')
);

create or replace function public.get_public_storefront(store_slug text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'organization', to_jsonb(o),
    'storefront', to_jsonb(s),
    'products', coalesce((select jsonb_agg(jsonb_build_object(
      'id',p.id,'name',p.name,'slug',p.slug,'description',p.description,'price',p.price,'currency',p.currency,
      'purchase_url',p.purchase_url,'provider',p.provider,'is_featured',p.is_featured,
      'images',coalesce((select jsonb_agg(jsonb_build_object('storage_path',pi.storage_path) order by pi.position)
        from public.product_images pi where pi.product_id=p.id),'[]'::jsonb)
    ) order by p.is_featured desc, p.position, p.created_at desc)
      from public.products p where p.organization_id=o.id and p.is_published = true),'[]'::jsonb)
  )
  from public.organizations o
  join public.storefronts s on s.organization_id=o.id
  where o.slug=store_slug and s.status='published'
  limit 1;
$$;

grant execute on function public.get_public_storefront(text) to anon, authenticated;
